def place(stations, geocode, cache, st_xy, dist):
    """STORES3 を記事へ振り分ける。戻り値は {slug: [gym, ...]}。既に同じ住所の店が載っている記事には足さない。"""
    import re
    out = {}
    for chain, store, address, access, short, hours in STORES3:
        lat, lng = geocode(address, cache)
        if not lat:
            continue
        best = None
        for st in stations:
            for n in re.split("・", st["short"]) + st.get("stations", []):
                n = n.replace("ヶ", "ケ")
                if n in st_xy:
                    d = dist(lat, lng, *st_xy[n])
                    if d <= 1000 and (best is None or d < best[1]):
                        best = (st["slug"], d)
        if best:
            out.setdefault(best[0], []).append({"chain": chain, "store": store, "address": address, "access": access,
                                                "short_access": short, "hours": hours})
    return out
